def mrow(name):
    r = rows[name]; return f"| {name} | {r['cv_mean']:.3f} ± {r['cv_std']:.3f} | {r['val_mae']:.3f} |"


def metrics_table_md():
    return "\n".join(["| Model | CV MAE (mean ± std, 2013-18 folds) | Validation MAE 2019-21 |", "|---|---|---|"] + [mrow(n) for n in rows])


def pf_table_md():
    return "\n".join(["| Criterion | Result | Detail |", "|---|---|---|"] + [f"| {p['criterion']} | **{p['result']}** | {p['detail']} |" for p in E["pass_fail"]])


